"""Minimal .env loader shared by the runner and ops scripts: KEY=VALUE lines, # comments, optional quotes.
Real environment variables always win over the file (os.environ.setdefault)."""
import os


def load(project_dir, filename=".env"):
    loaded = {}
    try:
        with open(os.path.join(project_dir, filename)) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line: continue
                k, v = line.split("=", 1); k, v = k.strip(), v.strip()
                if v[:1] in ("'", '"') and v[-1:] == v[:1] and len(v) >= 2: v = v[1:-1]
                elif " #" in v: v = v.split(" #", 1)[0].strip()
                loaded[k] = v; os.environ.setdefault(k, v)
    except OSError:
        pass
    return loaded


def parse_media_dirs(raw):
    """PLEX_MEDIA_DIRS: colon-separated absolute paths (PATH-style); duplicates dropped, paths normalised."""
    out = []
    for d in (raw or "").split(":"):
        d = d.strip()
        if d:
            d = os.path.normpath(d)
            if d not in out: out.append(d)
    return out


def media_compose_yaml(dirs):
    """docker-compose fragment with one read-only bind mount per media root, mounted at the same absolute path."""
    q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    lines = ["# GENERATED by ./setup-host.sh from PLEX_MEDIA_DIRS in .env (git-ignored). Re-run ./setup-host.sh after changing .env.",
             "services:", "  plex:", "    volumes:"]
    for d in dirs:
        lines += ["      - type: bind", "        source: " + q(d), "        target: " + q(d), "        read_only: true"]
    return "\n".join(lines) + "\n"
